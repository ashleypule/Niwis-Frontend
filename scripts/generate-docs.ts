type Any = Record<string, unknown>;

/** One-line description of a dataset payload: what it contains and its units. */
function describe(kind: Kind, d: Any): string {
  const title = d.title ? `${d.title}. ` : '';
  switch (kind) {
    case 'timeseries':
    case 'forecast': {
      const axes = (d.axes as Any[]).map((a) => `${a.label ?? ''}${a.unit ? ` (${a.unit})` : ''}`).join(' / ');
      const series = (d.series as Any[])
        .map((s) => s.name)
        .slice(0, 6)
        .join(', ');
      return `${title}x: ${d.xType}; y: ${axes}; series: ${series}${(d.series as Any[]).length > 6 ? ', …' : ''}`;
    }
    case 'breakdown':
      return `${title}unit: ${d.unit || '—'}; ${(d.categories as string[]).length} categories; series: ${(
        d.series as Any[]
      )
        .map((s) => s.name)
        .slice(0, 5)
        .join(', ')}`;
    case 'table':
      return `${title}columns: ${(d.columns as Any[]).map((c) => `${c.label}${c.unit ? ` (${c.unit})` : ''}`).join(', ')}`;
    case 'matrix':
      return `${title}${(d.rows as string[]).length} × ${(d.cols as string[]).length}; unit: ${d.unit || '—'}; scale: ${d.scale}`;
    case 'map':
      return `${d.title ?? ''} — ${d.geometry ?? (d.points ? 'points' : 'grid')}; scale: ${d.scale ?? '—'}; unit: ${d.unit || '—'}`;
  }
}

/** Shrink arrays so an example payload stays readable. */
function trim(v: unknown, depth = 0): unknown {
  if (Array.isArray(v)) {
    const t = v.slice(0, depth === 0 ? 3 : 4).map((x) => trim(x, depth + 1));
    return v.length > t.length ? [...t, `… ${v.length - t.length} more`] : t;
  }
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, trim(x, depth + 1)]));
  return v;
}

