/**
 * npm run naming:register — writes docs/NAMING_REGISTER.md from src/config/naming.ts (the derived metrics, units,
 * class labels and retired spellings) and the backend catalogue of every live module (database columns, shown as
 * sent). Reads the catalogues from the running backend (BACKEND_URL, default http://localhost:8000); when a module's
 * catalogue cannot be fetched it falls back to the recorded fixture (tests/fixtures/backend/{module}_categories.json).
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  CATALOGUE_ONLY_UNITS,
  CLASS_LABELS,
  DEPRECATED,
  UNIT_CANON,
  UNIT_DECIMALS,
  UNITS,
  canonUnit,
  metricRows,
} from '../src/config/naming';
import { SCALES } from '../src/config/palettes';

const BASE = (process.env.BACKEND_URL ?? 'http://localhost:8000').replace(/\/$/, '');
const ROOT = resolve(import.meta.dirname, '..');
const MODULES = (/^VITE_LIVE_MODULES=(.*)$/m.exec(readFileSync(resolve(ROOT, '.env.live'), 'utf8'))?.[1] ?? '')
  .split(',')
  .filter((m) => m && m !== 'ai');

interface Variable {
  column: string;
  label: string;
  name?: string;
  unit?: string;
  status: string;
  reason?: string;
  duplicateOf?: string;
  resolution?: string;
  chart?: string;
  note?: string;
  unitOverride?: string;
}
interface Table {
  id: string;
  table: string;
  label: string;
  specTag?: string;
  resolution?: string;
  variables: Variable[];
}

async function catalogue(module: string): Promise<{ tables: Table[]; from: string } | undefined> {
  try {
    const res = await fetch(`${BASE}/api/v1/${module}/categories`, { signal: AbortSignal.timeout(60_000) });
    if (res.ok) {
      const body = (await res.json()) as { tables?: Table[] };
      if (body.tables) return { tables: body.tables, from: 'backend' };
    }
  } catch {
    /* fall back to the recorded fixture */
  }
  const f = resolve(ROOT, 'tests/fixtures/backend', `${module}_categories.json`);
  if (!existsSync(f)) return undefined;
  const body = (JSON.parse(readFileSync(f, 'utf8')) as { body: { tables?: Table[] } }).body;
  return body.tables ? { tables: body.tables, from: 'fixture' } : undefined;
}

const cell = (s: string | number | undefined | null) =>
  String(s ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');
const dec = (unit: string) => {
  const r = UNIT_DECIMALS[unit];
  return r ? (r[0] === r[1] ? String(r[0]) : `${r[0]}–${r[1]}`) : '0–3';
};

async function main() {
  const lines: string[] = [];
  const p = (s = '') => lines.push(s);
  p('# NIWIS naming register');
  p();
  p(
    '> Generated by `npm run naming:register` from `src/config/naming.ts` (derived metrics, units, class labels, retired',
  );
  p('> spellings) and the backend catalogue of every live module (database columns). Do not edit by hand: change the');
  p(
    '> source and regenerate. `npm run naming:check` / the Playwright hybrid project (`tests/e2e/hybrid/naming.spec.ts`)',
  );
  p(
    '> report every rendered title, KPI label, axis, legend entry, table header, chip, pill and field that departs from it.',
  );
  p();
  p('## Rules');
  p();
  p(
    '1. **Database columns** keep the catalogue label and unit exactly as the backend sends them (`GET /{module}/categories`);',
  );
  p('   the frontend never renames them. Their rows are in "Database columns" below.');
  p(
    '2. **Derived or computed metrics** are named by their row in "Derived metrics" (from `src/config/metrics.ts`); a panel',
  );
  p(
    '   may add scope or period ("Rainfall anomaly (vs 2000–2026 mean)") but not another name for the variable. Derived',
  );
  p('   values are labelled as such ("Modelled", "Derived", "area-weighted mean") where the backend says so.');
  p(
    '3. **Units** are spelled one way (table below); `% FSC`, `m³/s`, `Mm³`, `cfu/100 mL`, `m bgl`, `mS/m`; indices and',
  );
  p('   ratios have no unit on a value and `index` on an axis. Temperature changes are in °C, never %.');
  p(
    '4. **Decimals**: standardised indices 2, coefficients 2–3, mm 0–1, % 0–1, Mm³ 0, °C 1 (per metric below; per unit for',
  );
  p('   tables and tooltips). Numbers use the SA style: space thousands separator, decimal point.');
  p(
    '5. **Class labels** are the lists below (D0 Abnormally Dry … D4 Exceptional Drought; Excellent / Good / Fair / Poor /',
  );
  p(
    '   Very Poor; storage bands; WQI bands), coloured from `src/config/palettes.ts`; legend breakpoints equal the thresholds.',
  );
  p(
    '6. **Conflicting names resolved**: `SPI-3` (not "SPI 3", "SPI-3 month"); `Heavy rain days (R20mm)` (not "R20mm days");',
  );
  p(
    '   `Standardised` (not "Standardized"); `Mm³/year`, `mm/year` (the catalogue spelling, not "/yr"); `ML/day` (not "Ml/day");',
  );
  p(
    '   `E. coli`; baselines from the response (never "1981–2010" over live data); `area in D2–D4` (not "SPI-3 ≤ −1.5").',
  );
  p();
  p('## Units');
  p();
  p('| Unit | Decimals | Retired spellings |');
  p('| --- | --- | --- |');
  for (const u of UNITS) {
    const retired = Object.entries(UNIT_CANON)
      .filter(([k, v]) => v === u && k !== u)
      .map(([k]) => `\`${k}\``);
    p(`| ${u ? `\`${u}\`` : '(none: index, ratio, count)'} | ${dec(u)} | ${retired.join(', ')} |`);
  }
  p();
  p(
    `Catalogue units shown as sent although the register spells them differently (backend item): ${CATALOGUE_ONLY_UNITS.map((u) => `\`${u}\``).join(', ')}.`,
  );
  p();
  p('## Class labels (colour scales)');
  p();
  p('| Scale | Title | Classes (least → most severe, or low → high) | Breakpoints |');
  p('| --- | --- | --- | --- |');
  for (const [id, labels] of Object.entries(CLASS_LABELS)) {
    const sc = (
      SCALES as Record<string, { title: string; bins: { label: string; min?: number; max?: number }[] } | undefined>
    )[id];
    const breaks = sc?.bins
      .map((b) =>
        b.min != null && b.max != null
          ? `${b.min}–${b.max}`
          : b.max != null
            ? `< ${b.max}`
            : b.min != null
              ? `≥ ${b.min}`
              : '',
      )
      .filter(Boolean)
      .join(', ');
    p(`| \`${id}\` | ${cell(sc?.title)} | ${labels.join(' / ')} | ${cell(breaks)} |`);
  }
  p();
  p('## Retired spellings');
  p();
  p('| Pattern | Use instead |');
  p('| --- | --- |');
  for (const d of DEPRECATED) p(`| \`${cell(d.re.source)}\` | ${cell(d.use)} |`);
  p();
  p('## Derived metrics');
  p();
  p(
    'One row per metric in `src/config/metrics.ts`. "Accepted spellings" are the other names the backend and the pages use',
  );
  p('for the same variable (KPI labels, series names); anything else is reported by the check.');
  p();
  p(
    '| Id | Display name | Unit | Decimals | Colour scale | Good direction | Class labels | Accepted spellings | Spec |',
  );
  p('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  const rows = metricRows();
  for (const r of rows)
    p(
      `| \`${r.id}\` | ${cell(r.name)} | ${r.unit ? `\`${r.unit}\`` : '—'} | ${r.decimals} | ${r.scale ? `\`${r.scale}\`` : '—'} | ${r.good} | ${cell(r.classes?.join(' / '))} | ${cell(r.aliases.join('; '))} | ${cell(r.section)} |`,
    );
  p();
  p('## Database columns');
  p();
  p('Label and unit as the backend catalogue sends them (one row per column and page; a column shown on several pages');
  p('appears once per page). Decimals follow the unit rule above. Colour: the chart series colour; no class labels.');
  p();
  let n = 0;
  const conflicts: string[] = [];
  for (const module of MODULES) {
    const cat = await catalogue(module);
    if (!cat) {
      p(`### ${module}`);
      p();
      p('No catalogue (the backend was not reachable and no fixture is recorded).');
      p();
      continue;
    }
    p(`### ${module} (${cat.from})`);
    p();
    p('| Table | Spec | Column | Display label | Unit | Decimals | Status | Note |');
    p('| --- | --- | --- | --- | --- | --- | --- | --- |');
    for (const t of cat.tables)
      for (const v of t.variables) {
        n++;
        const u = v.unit ?? '';
        const cu = canonUnit(u);
        if (u && cu !== u && !CATALOGUE_ONLY_UNITS.includes(u)) conflicts.push(`${t.table}.${v.column}: unit "${u}"`);
        p(
          `| ${cell(t.table)} | ${cell(t.specTag)} | \`${cell(v.column)}\` | ${cell(v.label)} | ${u ? `\`${u}\`` : '—'} | ${dec(cu)} | ${v.status} | ${cell(v.unitOverride ?? v.note ?? (v.duplicateOf ? `identical to ${v.duplicateOf}` : v.reason))} |`,
        );
      }
    p();
  }
  p('## Summary');
  p();
  p(`- Derived metrics: ${rows.length} (${rows.filter((r) => r.aliases.length).length} with accepted spellings).`);
  p(`- Database columns: ${n} rows over ${MODULES.length} modules.`);
  p(`- Units: ${UNITS.length - 1} spellings; retired spellings: ${Object.keys(UNIT_CANON).length}.`);
  p(`- Conflicting names resolved: ${DEPRECATED.length} patterns (table above).`);
  if (conflicts.length) p(`- Catalogue units outside the register's spelling (backend item): ${conflicts.join('; ')}.`);
  p();
  const out = resolve(ROOT, 'docs/NAMING_REGISTER.md');
  writeFileSync(out, `${lines.join('\n')}\n`);
  console.log(`docs/NAMING_REGISTER.md: ${rows.length} metrics, ${n} catalogue rows`);
}

void main();
