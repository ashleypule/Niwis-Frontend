#!/usr/bin/env node
/**
 * Derives typed reference data from public/geo/*.json into src/mocks/reference/generated.ts:
 * centroids and areas for provinces, WMAs, catchments and municipalities, the municipality → WMA
 * link, and a 0.25° grid clipped to South Africa with each cell's province / WMA / municipality.
 *
 * Usage: node scripts/build-reference.mjs
 */
import * as turf from '@turf/turf';
import fs from 'node:fs';

const load = (f) => JSON.parse(fs.readFileSync(`public/geo/${f}.json`, 'utf8'));
const r = (n, d = 3) => Math.round(n * 10 ** d) / 10 ** d;

const provinces = load('provinces');
const wmas = load('wmas');
const catchments = load('catchments');
const municipalities = load('municipalities');
const sa = load('south-africa');

const findIn = (fc, pt) => fc.features.find((f) => turf.booleanPointInPolygon(pt, f));
const centroid = (f) => {
  // centre of mass can fall outside concave shapes; fall back to an interior point
  try {
    const c = turf.centerOfMass(f);
    if (turf.booleanPointInPolygon(c, f)) return c;
  } catch {
    // multipart geometries with degenerate rings: fall through
  }
  return turf.pointOnFeature(f);
};
const area = (f) => Math.round(turf.area(f) / 1e6);

const prov = provinces.features.map((f) => {
  const c = centroid(f).geometry.coordinates;
  return { id: f.properties.id, name: f.properties.name, lon: r(c[0]), lat: r(c[1]), areaKm2: area(f) };
});
const wma = wmas.features.map((f) => {
  const c = centroid(f).geometry.coordinates;
  return { id: f.properties.id, name: f.properties.name, lon: r(c[0]), lat: r(c[1]), areaKm2: area(f) };
});
const catch_ = catchments.features
  .map((f) => {
    const cp = centroid(f);
    const c = cp.geometry.coordinates;
    const w = findIn(wmas, cp);
    const p = findIn(provinces, cp);
    return {
      id: f.properties.id,
      name: f.properties.name,
      wma: w?.properties.id ?? null,
      province: p?.properties.id ?? null,
      lon: r(c[0]),
      lat: r(c[1]),
      areaKm2: area(f),
    };
  })
  .filter((c) => c.province); // drop catchments whose centre lies outside SA (Lesotho / Eswatini headwaters)
const muni = municipalities.features.map((f) => {
  const cp = centroid(f);
  const c = cp.geometry.coordinates;
  const w = findIn(wmas, cp);
  return {
    id: f.properties.id,
    name: f.properties.name,
    province: f.properties.province,
    wma: w?.properties.id ?? 'WMA6',
    lon: r(c[0]),
    lat: r(c[1]),
    areaKm2: area(f),
  };
});

// 0.25° grid clipped to SA (Lesotho is a hole in the SA polygon, so it is excluded automatically)
const STEP = 0.25;
const saPoly = sa.features[0];
const cells = [];
for (let lat = -34.875; lat <= -22.125; lat += STEP) {
  for (let lon = 16.375; lon <= 32.875; lon += STEP) {
    const pt = turf.point([lon, lat]);
    if (!turf.booleanPointInPolygon(pt, saPoly)) continue;
    const p = findIn(provinces, pt);
    const w = findIn(wmas, pt);
    const mi = municipalities.features.findIndex((f) => turf.booleanPointInPolygon(pt, f));
    if (!p || mi < 0) continue;
    cells.push([r(lon), r(lat), p.properties.id, w?.properties.id ?? '', muni[mi].id]);
  }
}

const out = `// GENERATED by scripts/build-reference.mjs from public/geo — do not edit by hand.
import type { RegionRef, CatchmentRef, MunicipalityRef } from './types';

export const PROVINCE_GEO: RegionRef[] = ${JSON.stringify(prov)};
export const WMA_GEO: RegionRef[] = ${JSON.stringify(wma)};
export const CATCHMENTS: CatchmentRef[] = ${JSON.stringify(catch_)};
export const MUNICIPALITIES: MunicipalityRef[] = ${JSON.stringify(muni)};
/** [lon, lat, province, wma, municipality] — cell centres of a ${STEP}° grid clipped to SA */
export const GRID_STEP = ${STEP};
export const GRID_CELLS: [number, number, string, string, string][] = ${JSON.stringify(cells)};
`;
fs.mkdirSync('src/mocks/reference', { recursive: true });
fs.writeFileSync('src/mocks/reference/generated.ts', out);
console.log(
  `provinces ${prov.length}, wmas ${wma.length}, catchments ${catch_.length}, municipalities ${muni.length}, grid cells ${cells.length}`,
);
